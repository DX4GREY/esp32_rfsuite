namespace DisplayUi {

const ThemePalette& palette() {
    int index = static_cast<int>(appState.displayTheme);
    if (index < 0 || index >= DISPLAY_THEME_COUNT) {
        index = DISPLAY_THEME_CYBER;
    }
    return THEMES[index];
}

}  // namespace DisplayUi
